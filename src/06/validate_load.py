# ============================================================
# PDF 문서 검증 실습
# PDF를 읽은 후 텍스트가 정상적으로 추출되었는지 확인합니다.
# 빈 페이지, 전체 글자 수, 첫 페이지 내용을 점검합니다.
# ============================================================

from langchain_community.document_loaders import PyPDFLoader


# ------------------------------------------------------------
# 1. PDF 파일 로딩
# ------------------------------------------------------------

# PDF 파일을 읽어 페이지별 Document 객체로 가져옵니다.
loader = PyPDFLoader("../../data/manual.pdf")
docs = loader.load()


# ------------------------------------------------------------
# 2. 문서 검증 함수
# ------------------------------------------------------------

def validate(docs):

    print("=" * 45)
    print("문서 개수 :", len(docs))


    # --------------------------------------------------------
    # ① 내용이 거의 없는 페이지 확인
    # --------------------------------------------------------

    empty_pages = []

    # 각 페이지를 하나씩 확인합니다.
    for d in docs:

        # 페이지의 앞뒤 공백을 제거합니다.
        text = d.page_content.strip()

        # 글자가 10자보다 적으면 빈 페이지로 판단합니다.
        if len(text) < 10:

            # 페이지 번호를 저장합니다.
            page = d.metadata.get("page", "?")
            empty_pages.append(page)


    # 빈 페이지가 발견되었는지 확인합니다.
    if empty_pages:
        print("⚠ 내용이 거의 없는 페이지 :", empty_pages)
        print("  → 스캔 PDF일 수 있습니다.")
    else:
        print("✓ 빈 페이지 없음")


    # --------------------------------------------------------
    # ② 전체 글자 수 확인
    # --------------------------------------------------------

    total_len = 0

    # 모든 페이지의 글자 수를 더합니다.
    for d in docs:
        total_len += len(d.page_content)

    print("전체 글자 수 :", total_len)


    # --------------------------------------------------------
    # ③ 실제 추출된 내용 확인
    # --------------------------------------------------------

    print("-" * 45)

    # 첫 페이지의 앞 200자를 출력합니다.
    print("첫 페이지 내용 :", docs[0].page_content[:200])

    print("=" * 45)


# ------------------------------------------------------------
# 3. 문서 검증 실행
# ------------------------------------------------------------

validate(docs)