# ============================================================
# 텍스트 파일 로딩 실습
# notice.txt 파일을 읽어 Document 객체로 변환합니다.
# 본문 내용과 메타데이터를 확인합니다.
# ============================================================

from langchain_community.document_loaders import TextLoader


# ------------------------------------------------------------
# 1. 텍스트 파일 로더 생성
# ------------------------------------------------------------

# 읽어올 텍스트 파일의 경로를 지정합니다.
file_path = "../../data/notice.txt"

# UTF-8 방식으로 텍스트 파일을 읽도록 설정합니다.
loader = TextLoader(
    file_path,
    encoding="utf-8"
)


# ------------------------------------------------------------
# 2. 텍스트 파일 로딩
# ------------------------------------------------------------

# 파일을 읽어서 Document 객체의 리스트로 반환합니다.
docs = loader.load()


# ------------------------------------------------------------
# 3. 로딩 결과 확인
# ------------------------------------------------------------

# 생성된 Document 객체의 개수를 출력합니다.
print("문서 개수 :", len(docs))

# 첫 번째 Document의 본문 길이를 출력합니다.
print("본문 길이 :", len(docs[0].page_content), "글자")


# ------------------------------------------------------------
# 4. 본문 확인
# ------------------------------------------------------------

print()
print("--- 본문 앞 100자 ---")

# 첫 번째 Document의 본문 중 앞 100자만 출력합니다.
print(docs[0].page_content[:100])


# ------------------------------------------------------------
# 5. 메타데이터 확인
# ------------------------------------------------------------

print()
print("--- 메타데이터 ---")

# 첫 번째 Document에 저장된 파일 정보를 출력합니다.
print(docs[0].metadata)