# ============================================================
# PDF 파일 로딩 실습
# manual.pdf 파일을 읽어 페이지별 Document 객체로 변환합니다.
# 각 페이지의 번호와 본문 일부를 확인합니다.
# ============================================================

from langchain_community.document_loaders import PyPDFLoader


# ------------------------------------------------------------
# 1. PDF 파일 로더 생성
# ------------------------------------------------------------

# 읽어올 PDF 파일의 경로를 지정합니다.
file_path = "../../data/manual.pdf"

# PDF 파일을 읽기 위한 로더를 생성합니다.
loader = PyPDFLoader(file_path)


# ------------------------------------------------------------
# 2. PDF 파일 로딩
# ------------------------------------------------------------

# PDF를 읽어 페이지별 Document 객체의 리스트로 반환합니다.
docs = loader.load()


# ------------------------------------------------------------
# 3. 전체 페이지 수 확인
# ------------------------------------------------------------

# Document 개수는 PDF의 페이지 수와 같습니다.
print("총 페이지 수 :", len(docs))
print()


# ------------------------------------------------------------
# 4. 각 페이지의 내용 확인
# ------------------------------------------------------------

# docs에서 Document 객체를 하나씩 꺼냅니다.
for d in docs:

    # 현재 페이지 번호를 가져옵니다.
    page = d.metadata["page"]

    # 본문의 앞 60자만 가져옵니다.
    preview = d.page_content[:60]

    # 줄바꿈을 공백으로 바꿔 한 줄로 출력합니다.
    preview = preview.replace("\n", " ")

    # 페이지 번호와 본문 일부를 출력합니다.
    print(f"[{page}쪽] {preview} ...")