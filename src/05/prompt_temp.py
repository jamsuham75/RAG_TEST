# ============================================================
# PromptTemplate 사용 실습
# 문서와 질문이 들어갈 프롬프트 양식을 만듭니다.
# 실제 값을 넣어 LLM에 전달할 최종 프롬프트를 생성합니다.
# ============================================================

from langchain_core.prompts import PromptTemplate


# ------------------------------------------------------------
# 1. 프롬프트 양식 만들기
# ------------------------------------------------------------

# {doc}에는 문서 내용, {q}에는 사용자 질문이 들어갑니다.
template = """
다음 문서를 읽고 질문에 답하세요.
문서: {doc}
질문: {q}
답변:
"""


# ------------------------------------------------------------
# 2. PromptTemplate 객체 만들기
# ------------------------------------------------------------

# 사용할 변수와 프롬프트 양식을 지정합니다.
prompt = PromptTemplate(
    input_variables=["doc", "q"],
    template=template
)


# ------------------------------------------------------------
# 3. 실제 값을 넣어 프롬프트 완성하기
# ------------------------------------------------------------

# {doc}과 {q} 자리에 실제 값을 넣습니다.
result = prompt.format(
    doc="제품 색상은 검은색입니다",
    q="제품 색상은?"
)


# ------------------------------------------------------------
# 4. 완성된 프롬프트 확인하기
# ------------------------------------------------------------

# LLM에 전달할 최종 프롬프트를 출력합니다.
print(result)