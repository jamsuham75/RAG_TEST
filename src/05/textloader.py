# ============================================================
# 텍스트 파일 로딩 실습
# notice.txt 파일을 읽어 LangChain의 Document 객체로 변환합니다.
# 불러온 문서의 내용과 메타데이터를 확인합니다.
# ============================================================

from langchain_community.document_loaders import TextLoader


# ------------------------------------------------------------
# 1. 텍스트 파일 불러오기
# ------------------------------------------------------------

# 읽어올 텍스트 파일의 경로와 인코딩 방식을 지정합니다.
loader = TextLoader(
    "../../data/notice.txt",
    encoding="utf-8"
)

# 텍스트 파일을 읽어 Document 객체의 리스트로 가져옵니다.
documents = loader.load()


# ------------------------------------------------------------
# 2. 불러온 문서 확인하기
# ------------------------------------------------------------

# 불러온 Document 객체의 개수를 출력합니다.
print(f"로드: {len(documents)} 개")

# page_content에는 문서의 실제 텍스트 내용이 들어 있습니다.
print(f"내용: {documents[0].page_content}")

# metadata에는 원본 파일의 경로와 같은 부가정보가 들어 있습니다.
print(f"메타: {documents[0].metadata}")