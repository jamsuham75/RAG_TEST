# 4. 유형별 상세 진단을 실행합니다.
# ============================================================

def run_detail_tests():
    """4가지 유형의 질문을 차례대로 상세 진단합니다."""


    # --------------------------------------------------------
    # 질문을 4가지 유형으로 나눠 준비합니다.
    # --------------------------------------------------------

    test_groups = {

        "① 정상 (문서에 명확히 있음)": [
            "환불은 며칠 이내에 신청해야 하나요?",
            "고객센터 운영 시간은 언제인가요?",
        ],

        "② 표현 변경 (같은 뜻, 다른 단어)": [
            "반품하고 싶은데 언제까지 가능해요?",
            "상담원이랑 통화되는 시간 알려주세요",
        ],

        "③ 없는 내용 (문서에 없음)": [
            "대표이사 성함이 어떻게 되나요?",
            "작년 매출이 얼마인가요?",
        ],

        "④ 복합 질문 (여러 조항에 걸침)": [
            "환불과 교환의 조건 차이를 설명해주세요",
            "배송비는 어떤 경우에 누가 부담하나요?",
        ],
    }


    # --------------------------------------------------------
    # 질문 그룹을 하나씩 실행합니다.
    # --------------------------------------------------------

    for group_name, questions in test_groups.items():

        # 현재 질문 유형을 출력합니다.
        print(
            f"\n\n########## "
            f"{group_name} "
            f"##########"
        )


        # 해당 유형의 질문을 하나씩 진단합니다.
        for question in questions:

            diagnose(question)


