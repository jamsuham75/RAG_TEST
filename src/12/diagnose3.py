# ============================================================
# 1. 초기화
# ============================================================

# .env 파일에서 OpenAI API 키를 읽습니다.
load_dotenv()

# 저장된 벡터 DB를 불러옵니다.
store = get_store()

# 답변 생성에 사용할 LLM을 준비합니다.
llm = ChatOpenAI(
    model="gpt-4o-mini",
    temperature=0
)


# ============================================================
# 2. 질문 하나를 상세 진단합니다.
# ============================================================

def diagnose(question, k=3):
    """질문 하나의 검색 결과와 생성 답변을 상세히 확인합니다."""

    print("=" * 60)
    print("Q:", question)


    # --------------------------------------------------------
    # 1단계: 관련 문서를 검색합니다.
    # --------------------------------------------------------

    pairs = store.similarity_search_with_relevance_scores(
        question,
        k=k
    )


    # 검색 결과가 하나도 없으면 종료합니다.
    if not pairs:
        print("→ 【검색 실패】 결과가 0건입니다")
        return


    # --------------------------------------------------------
    # 2단계: 기준 점수 이상인 문서만 골라냅니다.
    # --------------------------------------------------------

    passed = []

    for document, score in pairs:

        if score >= MIN_SCORE:
            passed.append((document, score))


    # 검색 개수와 통과 개수를 출력합니다.
    print(
        f"검색 {len(pairs)}개 / "
        f"기준 통과 {len(passed)}개"
    )

    print("-" * 60)


    # --------------------------------------------------------
    # 3단계: 검색된 문서의 점수와 내용을 출력합니다.
    # --------------------------------------------------------

    for index, (document, score) in enumerate(pairs, start=1):

        # 기준 점수 통과 여부를 표시합니다.
        if score >= MIN_SCORE:
            mark = "✓"
        else:
            mark = "✗"

        # 문서 앞부분 70자만 가져옵니다.
        text = document.page_content[:70]

        # 줄바꿈을 공백으로 바꿉니다.
        text = text.replace("\n", " ")

        # 페이지 번호를 가져옵니다.
        page_no = document.metadata["page_no"]

        # 검색 결과를 출력합니다.
        print(
            f"{mark} [{index}] "
            f"{score:.3f} "
            f"p.{page_no} "
            f"{text}..."
        )


    # --------------------------------------------------------
    # 4단계: 기준을 통과한 문서가 없으면 종료합니다.
    # --------------------------------------------------------

    if not passed:
        print("\n→ 【검색 실패】 기준을 넘는 조각이 없습니다")
        return


    # --------------------------------------------------------
    # 5단계: 통과한 결과에서 Document만 꺼냅니다.
    # --------------------------------------------------------

    documents = []

    for document, score in passed:
        documents.append(document)


    # --------------------------------------------------------
    # 6단계: 검색된 문서를 Context로 만듭니다.
    # --------------------------------------------------------

    context = build_context(documents)


    # --------------------------------------------------------
    # 7단계: LLM에게 전달할 프롬프트를 만듭니다.
    # --------------------------------------------------------

    prompt = (
        "아래 자료만 근거로 답하세요.\n"
        "자료에 없으면 "
        "'자료에서 확인할 수 없습니다'라고 답하세요.\n\n"
        f"[자료]\n{context}\n\n"
        f"[질문] {question}"
    )


    # --------------------------------------------------------
    # 8단계: LLM에게 질문하고 답변을 받습니다.
    # --------------------------------------------------------

    response = llm.invoke(prompt)

    answer = response.content


    # --------------------------------------------------------
    # 9단계: 최종 답변과 진단 기준을 출력합니다.
    # --------------------------------------------------------

    print("\nA:", answer)

    print("\n👉 판단: 위 조각들 안에 정답이 있었는가?")
    print("   있는데 답이 틀렸다면 → 생성 문제 (13차시)")
    print("   없다면              → 검색 문제 (7·11차시)")

    print("=" * 60)


# ============================================================
# 3. 전체 테스트 질문의 정답률을 평가합니다.
# ============================================================

def score():
    """여러 질문을 자동 실행하여 전체 정답률을 계산합니다."""


    # --------------------------------------------------------
    # 평가용 질문과 정답 키워드를 준비합니다.
    # --------------------------------------------------------

    tests = [

        {
            "question": "환불은 며칠 이내인가요?",
            "keywords": ["7일", "일주일"]
        },

        {
            "question": "교환은 며칠 이내인가요?",
            "keywords": ["30일"]
        },

        {
            "question": "고객센터 운영 시간은?",
            "keywords": ["09:00", "18:00", "평일"]
        },

        {
            "question": "대표이사 이름은?",
            "keywords": ["확인할 수 없"]
        },

        # 필요하면 여기에 테스트 질문을 추가합니다.
    ]


    # 맞은 질문의 개수를 저장합니다.
    hit_count = 0

    # 실패한 질문과 답변을 저장합니다.
    failed_tests = []


    # --------------------------------------------------------
    # 테스트 질문을 하나씩 실행합니다.
    # --------------------------------------------------------

    for test in tests:

        # 현재 질문을 가져옵니다.
        question = test["question"]

        # 정답으로 인정할 키워드를 가져옵니다.
        keywords = test["keywords"]


        # ----------------------------------------------------
        # 1단계: 관련 문서를 검색합니다.
        # ----------------------------------------------------

        pairs = store.similarity_search_with_relevance_scores(
            question,
            k=3
        )


        # ----------------------------------------------------
        # 2단계: 기준 점수 이상인 문서만 사용합니다.
        # ----------------------------------------------------

        documents = []

        for document, score in pairs:

            if score >= MIN_SCORE:
                documents.append(document)


        # ----------------------------------------------------
        # 3단계: 검색 결과가 없으면 LLM을 호출하지 않습니다.
        # ----------------------------------------------------

        if not documents:

            answer = "자료에서 확인할 수 없습니다"

        else:

            # 검색 문서를 Context로 만듭니다.
            context = build_context(documents)

            # LLM에게 전달할 프롬프트를 만듭니다.
            prompt = (
                "아래 자료만 근거로 답하세요.\n"
                "자료에 없으면 "
                "'자료에서 확인할 수 없습니다'라고 답하세요.\n\n"
                f"[자료]\n{context}\n\n"
                f"[질문] {question}"
            )

            # LLM에게 질문합니다.
            response = llm.invoke(prompt)

            # 답변 내용만 가져옵니다.
            answer = response.content


        # ----------------------------------------------------
        # 4단계: 정답 키워드가 포함되어 있는지 확인합니다.
        # ----------------------------------------------------

        is_correct = False

        for keyword in keywords:

            if keyword in answer:
                is_correct = True
                break


        # ----------------------------------------------------
        # 5단계: 정답과 오답을 기록합니다.
        # ----------------------------------------------------

        if is_correct:

            hit_count += 1

        else:

            failed_tests.append(
                (question, answer[:60])
            )


    # --------------------------------------------------------
    # 6단계: 전체 정답률을 계산합니다.
    # --------------------------------------------------------

    total_count = len(tests)

    accuracy = hit_count / total_count * 100


    # --------------------------------------------------------
    # 7단계: 평가 결과를 출력합니다.
    # --------------------------------------------------------

    print("\n" + "=" * 60)

    print(
        f"정답률: "
        f"{hit_count}/{total_count} "
        f"= {accuracy:.0f}%"
    )

    print("=" * 60)


    # --------------------------------------------------------
    # 8단계: 실패한 질문을 출력합니다.
    # --------------------------------------------------------

    print("\n■ 실패한 질문")

    for question, answer in failed_tests:

        print(f"  · {question}")

        print(f"    → {answer}...")


    print(f"\n총 {len(failed_tests)}개 실패")

    print("=" * 60)


