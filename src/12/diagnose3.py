# 5. 실행 방법을 출력합니다.
# ============================================================

def print_usage():
    """프로그램의 실행 방법을 출력합니다."""

    print("사용법:")

    print(
        "  python diagnose.py score"
        "          # 전체 정답률 평가"
    )

    print(
        "  python diagnose.py detail"
        "         # 상세 진단"
    )

    print(
        '  python diagnose.py "질문내용"'
        "     # 개별 질문 진단"
    )


# ============================================================
# 6. 프로그램 실행
# ============================================================

if __name__ == "__main__":


    # --------------------------------------------------------
    # 명령어가 입력되었는지 확인합니다.
    # --------------------------------------------------------

    if len(sys.argv) > 1:

        command = sys.argv[1]


        # ----------------------------------------------------
        # score를 입력하면 전체 정답률을 평가합니다.
        # ----------------------------------------------------

        if command == "score":

            score()


        # ----------------------------------------------------
        # detail을 입력하면 유형별 진단을 실행합니다.
        # ----------------------------------------------------

        elif command == "detail":

            run_detail_tests()


        # ----------------------------------------------------
        # 그 외의 문자열은 질문으로 사용합니다.
        # ----------------------------------------------------

        else:

            diagnose(command)


    # --------------------------------------------------------
    # 아무 옵션도 없으면 사용법을 보여줍니다.
    # --------------------------------------------------------

    else:

        print_usage()