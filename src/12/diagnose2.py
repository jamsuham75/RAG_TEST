# ============================================================
# diagnose.py
# RAG의 검색 결과와 생성 답변을 직접 확인하는 진단 프로그램입니다.
# 정상/표현변경/없는내용/복합질문의 4가지 유형을 순서대로 테스트합니다.
# ============================================================

import os
import sys

from dotenv import load_dotenv
from langchain_openai import ChatOpenAI


# ------------------------------------------------------------
# 10차시와 11차시의 파이썬 파일을 사용할 수 있도록 경로를 추가합니다.
# ------------------------------------------------------------

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))

sys.path.insert(0, os.path.join(CURRENT_DIR, "..", "10"))
sys.path.insert(0, os.path.join(CURRENT_DIR, "..", "11"))


# ------------------------------------------------------------
# 이전 차시에서 만든 기능을 가져옵니다.
# ------------------------------------------------------------

from indexer import get_store
from retriever import build_context, MIN_SCORE


# ------------------------------------------------------------
# 실행에 필요한 환경을 준비합니다.
# ------------------------------------------------------------

# .env 파일의 API 키를 불러옵니다.
load_dotenv()

# 저장된 벡터 DB를 불러옵니다.
store = get_store()

# 답변 생성에 사용할 LLM을 준비합니다.
llm = ChatOpenAI(
    model="gpt-4o-mini",
    temperature=0
)


# ============================================================
# 질문 하나를 검색부터 답변 생성까지 상세하게 진단합니다.
# ============================================================

def diagnose(question, k=3):

    print("=" * 60)
    print("Q:", question)


    # --------------------------------------------------------
    # 1. 질문과 관련된 문서를 검색합니다.
    # --------------------------------------------------------

    pairs = store.similarity_search_with_relevance_scores(
        question,
        k=k
    )


    # 검색 결과가 하나도 없으면 종료합니다.
    if not pairs:
        print("→ 【검색 실패】 결과가 0건입니다")
        return


    # --------------------------------------------------------
    # 2. 검색 점수가 기준 이상인 문서만 골라냅니다.
    # --------------------------------------------------------

    passed = []

    for document, score in pairs:

        if score >= MIN_SCORE:
            passed.append((document, score))


    # 검색 결과 개수를 출력합니다.
    print(
        f"검색 {len(pairs)}개 / "
        f"기준 통과 {len(passed)}개"
    )

    print("-" * 60)


    # --------------------------------------------------------
    # 3. 검색된 모든 문서와 점수를 확인합니다.
    # --------------------------------------------------------

    for index, (document, score) in enumerate(pairs, start=1):

        # 점수 기준 통과 여부를 표시합니다.
        if score >= MIN_SCORE:
            mark = "✓"
        else:
            mark = "✗"

        # 문서 앞부분 70자만 가져옵니다.
        text = document.page_content[:70]

        # 줄바꿈을 제거하여 한 줄로 출력합니다.
        text = text.replace("\n", " ")

        # 페이지 번호를 가져옵니다.
        page_no = document.metadata["page_no"]

        # 검색 결과를 출력합니다.
        print(
            f"{mark} [{index}] "
            f"{score:.3f} "
            f"p.{page_no} "
            f"{text}..."
        )


    # --------------------------------------------------------
    # 4. 기준을 통과한 문서가 없으면 검색 실패입니다.
    # --------------------------------------------------------

    if not passed:
        print("\n→ 【검색 실패】 기준을 넘는 조각이 없습니다")
        return


    # --------------------------------------------------------
    # 5. 통과한 결과에서 Document만 꺼냅니다.
    # --------------------------------------------------------

    docs = []

    for document, score in passed:
        docs.append(document)


    # --------------------------------------------------------
    # 6. 검색된 문서를 LLM에게 전달할 Context로 만듭니다.
    # --------------------------------------------------------

    context = build_context(docs)


    # --------------------------------------------------------
    # 7. LLM에게 전달할 프롬프트를 만듭니다.
    # --------------------------------------------------------

    prompt = (
        "아래 자료만 근거로 답하세요.\n"
        "자료에 없으면 "
        "'자료에서 확인할 수 없습니다'라고 답하세요.\n\n"
        f"[자료]\n{context}\n\n"
        f"[질문] {question}"
    )


    # --------------------------------------------------------
    # 8. LLM에게 질문하고 답변을 받습니다.
    # --------------------------------------------------------

    response = llm.invoke(prompt)

    answer = response.content


    # --------------------------------------------------------
    # 9. 생성된 답변을 출력합니다.
    # --------------------------------------------------------

    print("\nA:", answer)


    # --------------------------------------------------------
    # 10. 검색 문제인지 생성 문제인지 판단 기준을 보여줍니다.
    # --------------------------------------------------------

    print("\n👉 판단: 위 조각들 안에 정답이 있었는가?")
    print("   있는데 답이 틀렸다면 → 생성 문제 (13차시)")
    print("   없다면              → 검색 문제 (7·11차시)")

    print("=" * 60)


# ============================================================
# 이 파일을 직접 실행했을 때 테스트를 진행합니다.
# ============================================================

if __name__ == "__main__":


    # --------------------------------------------------------
    # 4가지 유형별 테스트 질문을 준비합니다.
    # --------------------------------------------------------

    TESTS = {

        "① 정상 (문서에 명확히 있음)": [
            "환불은 며칠 이내에 신청해야 하나요?",
            "고객센터 운영 시간은 언제인가요?",
        ],

        "② 표현 변경 (같은 뜻, 다른 단어)": [
            "반품하고 싶은데 언제까지 가능해요?",
            "상담원이랑 통화되는 시간 알려주세요",
        ],

        "③ 없는 내용 (문서에 없음)": [
            "대표이사 성함이 어떻게 되나요?",
            "작년 매출이 얼마인가요?",
        ],

        "④ 복합 질문 (여러 조항에 걸침)": [
            "환불과 교환의 조건 차이를 설명해주세요",
            "배송비는 어떤 경우에 누가 부담하나요?",
        ],
    }


    # --------------------------------------------------------
    # 테스트 그룹을 하나씩 실행합니다.
    # --------------------------------------------------------

    for group, questions in TESTS.items():

        # 현재 테스트 유형을 출력합니다.
        print(f"\n\n########## {group} ##########")


        # 해당 그룹의 질문을 하나씩 실행합니다.
        for question in questions:

            diagnose(question)

            # 결과를 확인한 후 Enter를 누르면 다음 질문으로 넘어갑니다.
            input("\n[Enter 키로 다음 질문 진행]")