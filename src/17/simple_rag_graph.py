# ============================================================
# LangGraph 기본 구조 실습
# State를 이용해 검색 Node와 답변 Node 사이에서 데이터를 전달합니다.
# search → answer 순서로 실행되는 가장 단순한 Graph를 만듭니다.
# ============================================================

from typing import TypedDict
from langgraph.graph import StateGraph


# ============================================================
# 1. State 정의
# ============================================================
# Graph의 여러 Node가 함께 사용할 데이터 구조입니다.

class SimpleRAGState(TypedDict):

    # 사용자의 질문
    query: str

    # 검색 결과
    results: list

    # 최종 답변
    answer: str


# ============================================================
# 2. 검색 Node
# ============================================================
# 사용자의 질문을 확인하고 검색 결과를 State에 저장합니다.

def search_node(state: SimpleRAGState):

    # State에서 질문을 가져옵니다.
    query = state["query"]

    print(f"[검색 Node] 질문: {query}")

    # 실제 검색 대신 미리 만든 검색 결과를 사용합니다.
    results = [
        "문서1: 제품 가격은 10,000원입니다.",
        "문서2: 배송비는 무료입니다.",
        "문서3: 현재 할인 행사가 진행 중입니다."
    ]

    # 검색 결과를 State에 저장합니다.
    state["results"] = results

    # 변경된 State를 다음 Node로 전달합니다.
    return state


# ============================================================
# 3. 답변 Node
# ============================================================
# 검색 결과를 확인하고 최종 답변을 State에 저장합니다.

def answer_node(state: SimpleRAGState):

    # 검색 결과를 출력합니다.
    print(f"[답변 Node] 검색 결과: {state['results']}")

    # 실제 LLM 대신 미리 만든 답변을 사용합니다.
    answer = "검색 결과를 바탕으로 만든 답변입니다."

    # 생성한 답변을 State에 저장합니다.
    state["answer"] = answer

    # 변경된 State를 반환합니다.
    return state


# ============================================================
# 4. Graph 생성
# ============================================================
# SimpleRAGState를 사용하는 Graph를 만듭니다.

graph = StateGraph(SimpleRAGState)


# ============================================================
# 5. Node 등록
# ============================================================
# 사용할 함수를 Graph의 Node로 등록합니다.

graph.add_node("search", search_node)
graph.add_node("answer", answer_node)


# ============================================================
# 6. Edge 연결
# ============================================================
# search가 끝나면 answer를 실행하도록 연결합니다.

graph.add_edge("search", "answer")


# ============================================================
# 7. 시작점과 종료점 설정
# ============================================================

# Graph는 search에서 시작합니다.
graph.set_entry_point("search")

# Graph는 answer에서 종료합니다.
graph.set_finish_point("answer")


# ============================================================
# 8. Graph 컴파일
# ============================================================
# 설계한 Graph를 실제 실행 가능한 형태로 만듭니다.

app = graph.compile()


# ============================================================
# 9. 초기 State 생성
# ============================================================
# Graph에 처음 전달할 데이터를 준비합니다.

state = {
    "query": "가격이 얼마야?",
    "results": [],
    "answer": ""
}


# ============================================================
# 10. Graph 실행
# ============================================================
# 초기 State를 넣어 Graph를 실행합니다.

result = app.invoke(state)


# ============================================================
# 11. 최종 결과 확인
# ============================================================

print("\n===== 최종 결과 =====")
print("질문:", result["query"])
print("검색 결과:", result["results"])
print("답변:", result["answer"])