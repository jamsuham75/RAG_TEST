# ============================================================
# LangGraph Conditional Edge 실습
# 검색 결과가 있으면 answer로 이동하고,
# 검색 결과가 없으면 다시 search로 이동하는 조건 분기를 만듭니다.
# ============================================================

from typing import TypedDict
from langgraph.graph import StateGraph


# ============================================================
# 1. State 정의
# ============================================================
# Graph의 여러 Node가 함께 사용할 데이터 구조입니다.

class SimpleRAGState(TypedDict):

    # 사용자의 질문
    query: str

    # 검색 결과
    results: list

    # 최종 답변
    answer: str


# ============================================================
# 2. 검색 Node
# ============================================================
# 질문에 "가격"이 있으면 검색 성공으로 가정합니다.

def search_node(state: SimpleRAGState):

    # State에서 질문을 가져옵니다.
    query = state["query"]

    print(f"\n[검색 Node] 질문: {query}")

    # "가격"이 있으면 검색 성공으로 가정합니다.
    if "가격" in query:

        results = [
            "문서1: 제품 가격은 10,000원입니다.",
            "문서2: 배송비는 무료입니다.",
            "문서3: 현재 할인 행사가 진행 중입니다."
        ]

    # "가격"이 없으면 검색 실패로 가정합니다.
    else:
        results = []

    # 검색 결과를 State에 저장합니다.
    state["results"] = results

    print("[검색 Node] 검색 결과:", results)

    # 변경된 State를 반환합니다.
    return state


# ============================================================
# 3. 답변 Node
# ============================================================
# 검색 결과가 있을 때 최종 답변을 만듭니다.

def answer_node(state: SimpleRAGState):

    print("\n[답변 Node] 검색 결과를 이용하여 답변을 생성합니다.")

    # 실제 LLM 대신 미리 만든 답변을 사용합니다.
    answer = "검색 결과를 바탕으로 만든 답변입니다."

    # 답변을 State에 저장합니다.
    state["answer"] = answer

    # 변경된 State를 반환합니다.
    return state


# ============================================================
# 4. 검색 결과 판단
# ============================================================
# 검색 결과가 있는지 확인하여 다음 경로를 결정합니다.

def check_search_quality(state: SimpleRAGState):

    print("\n[조건 검사] 검색 결과를 확인합니다.")

    # 검색 결과가 하나 이상 있으면 good을 반환합니다.
    if len(state["results"]) > 0:
        print("[조건 검사] 검색 결과 있음 → good")
        return "good"

    # 검색 결과가 없으면 bad를 반환합니다.
    else:
        print("[조건 검사] 검색 결과 없음 → bad")
        return "bad"


# ============================================================
# 5. Graph 생성
# ============================================================

graph = StateGraph(SimpleRAGState)


# ============================================================
# 6. Node 등록
# ============================================================

graph.add_node("search", search_node)
graph.add_node("answer", answer_node)


# ============================================================
# 7. Conditional Edge 연결
# ============================================================
# search 실행 후 결과에 따라 다음 Node를 결정합니다.

graph.add_conditional_edges(
    "search",
    check_search_quality,
    {
        "good": "answer",     # 검색 성공 → answer
        "bad": "search"       # 검색 실패 → 다시 search
    }
)


# ============================================================
# 8. 시작점과 종료점 설정
# ============================================================

# Graph는 search에서 시작합니다.
graph.set_entry_point("search")

# Graph는 answer에서 종료합니다.
graph.set_finish_point("answer")


# ============================================================
# 9. Graph 컴파일
# ============================================================
# 설계한 Graph를 실행 가능한 형태로 만듭니다.

app = graph.compile()


# ============================================================
# 10. 초기 State 생성
# ============================================================

state = {
    "query": "제품 가격이 얼마야?",
    "results": [],
    "answer": ""
}


# ============================================================
# 11. Graph 실행
# ============================================================
# 현재 질문에는 "가격"이 없으므로 계속 search로 돌아갑니다.
# LangGraph의 실행 제한에 도달하면 오류가 발생하며 중단됩니다.

result = app.invoke(state)


# ============================================================
# 12. 최종 결과 확인
# ============================================================

print("\n===== 최종 결과 =====")
print("질문:", result["query"])
print("검색 결과:", result["results"])
print("답변:", result["answer"])