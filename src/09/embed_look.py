# ============================================================
# 문장을 임베딩 벡터로 변환하고 벡터의 기본 정보를 확인합니다.
# 벡터의 차원 수, 앞부분 값, 최댓값과 최솟값을 출력합니다.
# ============================================================

from langchain_openai import OpenAIEmbeddings
from dotenv import load_dotenv


# ------------------------------------------------------------
# 1. 환경 변수 불러오기
# ------------------------------------------------------------

# .env 파일에 저장된 OPENAI_API_KEY를 불러옵니다.
load_dotenv()


# ------------------------------------------------------------
# 2. 임베딩 모델 준비
# ------------------------------------------------------------

# 문장을 숫자 벡터로 변환할 임베딩 모델을 생성합니다.
emb = OpenAIEmbeddings(
    model="text-embedding-3-small"
)


# ------------------------------------------------------------
# 3. 문장을 임베딩 벡터로 변환
# ------------------------------------------------------------

# 질문 문장을 숫자로 이루어진 벡터로 변환합니다.
vec = emb.embed_query("환불 규정이 궁금합니다")


# ------------------------------------------------------------
# 4. 벡터의 기본 정보 출력
# ------------------------------------------------------------

# 벡터에 들어 있는 숫자의 개수를 출력합니다.
print("차원 수 :", len(vec))


# 벡터의 앞 10개 값을 저장할 리스트입니다.
first_10 = []

# 앞에서부터 10개의 값을 하나씩 가져옵니다.
for value in vec[:10]:

    # 보기 편하도록 소수점 넷째 자리까지 반올림합니다.
    first_10.append(round(value, 4))

# 앞 10개의 값을 출력합니다.
print("앞 10개 :", first_10)


# 벡터에서 가장 큰 값을 출력합니다.
print("최댓값 :", round(max(vec), 4))

# 벡터에서 가장 작은 값을 출력합니다.
print("최솟값 :", round(min(vec), 4))