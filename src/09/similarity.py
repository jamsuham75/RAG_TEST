# ============================================================
# 두 문장을 임베딩 벡터로 변환한 후 코사인 유사도를 계산합니다.
# 여러 문장 쌍을 비교하여 의미가 비슷할수록 점수가 어떻게 달라지는지 확인합니다.
# ============================================================

import numpy as np
from langchain_openai import OpenAIEmbeddings
from dotenv import load_dotenv


# ------------------------------------------------------------
# 1. 환경 변수 불러오기
# ------------------------------------------------------------

# .env 파일에 저장된 OPENAI_API_KEY를 불러옵니다.
load_dotenv()


# ------------------------------------------------------------
# 2. 임베딩 모델 준비
# ------------------------------------------------------------

# 문장을 숫자 벡터로 변환할 임베딩 모델을 생성합니다.
emb = OpenAIEmbeddings(
    model="text-embedding-3-small"
)


# ------------------------------------------------------------
# 3. 두 문장의 코사인 유사도를 계산하는 함수
# ------------------------------------------------------------

def sim(sentence1, sentence2):

    # 첫 번째 문장을 임베딩 벡터로 변환합니다.
    vector1 = emb.embed_query(sentence1)

    # 두 번째 문장을 임베딩 벡터로 변환합니다.
    vector2 = emb.embed_query(sentence2)

    # 계산을 위해 리스트를 NumPy 배열로 변환합니다.
    vector1 = np.array(vector1)
    vector2 = np.array(vector2)

    # 두 벡터의 내적을 계산합니다.
    dot_product = np.dot(vector1, vector2)

    # 첫 번째 벡터의 길이를 계산합니다.
    length1 = np.linalg.norm(vector1)

    # 두 번째 벡터의 길이를 계산합니다.
    length2 = np.linalg.norm(vector2)

    # 코사인 유사도를 계산합니다.
    similarity = dot_product / (length1 * length2)

    # 계산된 유사도를 실수로 반환합니다.
    return float(similarity)


# ------------------------------------------------------------
# 4. 비교할 문장 준비
# ------------------------------------------------------------

# 의미가 비슷한 문장부터 관련 없는 문장까지 준비합니다.
PAIRS = [
    ("환불 규정", "반품 절차"),
    ("비밀번호 변경", "패스워드 재설정"),
    ("제품이 고장났어요", "기기 불량 신고"),
    ("환불 규정", "배송 안내"),
    ("환불 규정", "오늘 점심 메뉴"),
]


# ------------------------------------------------------------
# 5. 문장별 유사도 확인
# ------------------------------------------------------------

# 문장 쌍을 하나씩 가져옵니다.
for sentence1, sentence2 in PAIRS:

    # 두 문장의 코사인 유사도를 계산합니다.
    score = sim(sentence1, sentence2)

    # 계산된 유사도와 두 문장을 출력합니다.
    print(f"{score:.3f}   {sentence1:<18} <-> {sentence2}")