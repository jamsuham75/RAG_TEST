# ============================================================
# Streamlit 웹 화면에서 사용자의 질문을 입력받고,
# RAG 시스템의 답변과 참고 문서 페이지를 화면에 표시합니다.
# RAG 초기화는 cache_resource를 사용해 한 번만 수행합니다.
# ============================================================

import streamlit as st


# ============================================================
# 1. RAG 기능 준비
# ============================================================
# Streamlit이 화면을 다시 실행하더라도
# RAG 관련 객체를 매번 새로 만들지 않도록 캐시합니다.
# ============================================================

@st.cache_resource
def load_rag():

    # rag.py의 ask 함수를 가져옵니다.
    from rag import ask

    # 가져온 ask 함수를 반환합니다.
    return ask


# 캐시된 ask 함수를 가져옵니다.
ask = load_rag()


# ============================================================
# 2. Streamlit 페이지 설정
# ============================================================

# 브라우저 탭 제목과 아이콘을 설정합니다.
st.set_page_config(
    page_title="문서 Q&A",
    page_icon="■"
)


# 화면 제목을 출력합니다.
st.title("■ 문서 기반 질의응답")


# ============================================================
# 3. 대화 기록 준비
# ============================================================

# 최초 실행이면 대화 기록을 저장할 리스트를 만듭니다.
if "history" not in st.session_state:
    st.session_state.history = []


# ============================================================
# 4. 사용자 질문 입력
# ============================================================

# 채팅 입력창에서 질문을 받습니다.
question = st.chat_input(
    "궁금한 것을 물어보세요"
)


# ============================================================
# 5. 질문이 입력되면 RAG 실행
# ============================================================

if question:

    # 답변을 만드는 동안 로딩 메시지를 표시합니다.
    with st.spinner("자료를 찾는 중..."):

        # RAG 시스템에 질문을 전달합니다.
        result = ask(question)

    # 질문과 결과를 대화 기록에 저장합니다.
    st.session_state.history.append(
        (question, result)
    )


# ============================================================
# 6. 지금까지의 대화 기록 출력
# ============================================================

for question, result in st.session_state.history:

    # --------------------------------------------------------
    # 사용자 질문 출력
    # --------------------------------------------------------

    with st.chat_message("user"):
        st.write(question)


    # --------------------------------------------------------
    # AI 답변 출력
    # --------------------------------------------------------

    with st.chat_message("assistant"):

        # RAG가 생성한 답변을 출력합니다.
        st.write(result["answer"])


        # ----------------------------------------------------
        # 참고 자료 출력
        # ----------------------------------------------------

        # 출처가 있을 때만 참고 정보를 출력합니다.
        if result["sources"]:

            # 중복되지 않는 페이지 번호를 저장합니다.
            pages = []

            # 출처를 하나씩 확인합니다.
            for source in result["sources"]:

                page = source["page"]

                # 아직 저장되지 않은 페이지 번호만 추가합니다.
                if page not in pages:
                    pages.append(page)


            # 페이지 번호를 오름차순으로 정렬합니다.
            pages.sort()


            # 페이지 번호를 문자열로 변환합니다.
            page_texts = []

            for page in pages:
                page_texts.append(str(page))


            # 1, 2, 3 형태의 문자열로 만듭니다.
            page_text = ", ".join(page_texts)


            # 첫 번째 출처에서 파일 이름을 가져옵니다.
            filename = result["sources"][0]["file"]


            # 참고 문서와 페이지를 출력합니다.
            st.caption(
                f"※ 참고: {filename} "
                f"{page_text}페이지"
            )