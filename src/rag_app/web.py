# ============================================================
# Streamlit 웹 화면에서 사용자의 질문을 입력받고,
# RAG 시스템의 답변과 참고 문서 페이지를 화면에 표시합니다.
# 이전 질문과 답변은 session_state에 저장하여 계속 보여줍니다.
# ============================================================

import streamlit as st

from rag import ask


# ============================================================
# 1. Streamlit 페이지 기본 설정
# ============================================================

# 브라우저 탭 제목과 아이콘을 설정합니다.
st.set_page_config(
    page_title="문서 Q&A",
    page_icon="■"
)


# 화면 제목을 출력합니다.
st.title("■ 문서 기반 질의응답")


# ============================================================
# 2. 대화 기록 준비
# ============================================================

# 최초 실행이라면 대화 기록을 저장할 리스트를 만듭니다.
if "history" not in st.session_state:
    st.session_state.history = []


# ============================================================
# 3. 사용자 질문 입력
# ============================================================

# 화면 아래의 채팅 입력창에서 질문을 받습니다.
question = st.chat_input(
    "궁금한 것을 물어보세요"
)


# ============================================================
# 4. 질문이 입력되면 RAG 실행
# ============================================================

if question:

    # 답변을 만드는 동안 로딩 메시지를 표시합니다.
    with st.spinner("자료를 찾는 중..."):

        # RAG 시스템에 질문을 전달합니다.
        result = ask(question)

    # 질문과 결과를 대화 기록에 저장합니다.
    st.session_state.history.append(
        (question, result)
    )


# ============================================================
# 5. 지금까지의 대화 기록 출력
# ============================================================

for question, result in st.session_state.history:

    # --------------------------------------------------------
    # 사용자 질문 출력
    # --------------------------------------------------------

    with st.chat_message("user"):
        st.write(question)


    # --------------------------------------------------------
    # AI 답변 출력
    # --------------------------------------------------------

    with st.chat_message("assistant"):

        # RAG가 생성한 답변을 출력합니다.
        st.write(result["answer"])


        # ----------------------------------------------------
        # 참고 자료 출력
        # ----------------------------------------------------

        # 검색된 출처가 있을 때만 참고 페이지를 출력합니다.
        if result["sources"]:

            # 중복되지 않는 페이지 번호를 저장합니다.
            pages = []

            # 검색된 출처를 하나씩 확인합니다.
            for source in result["sources"]:

                page = source["page"]

                # 아직 추가하지 않은 페이지 번호만 저장합니다.
                if page not in pages:
                    pages.append(page)


            # 페이지 번호를 작은 순서대로 정렬합니다.
            pages.sort()


            # 숫자 페이지를 문자열로 변환합니다.
            page_texts = []

            for page in pages:
                page_texts.append(str(page))


            # 1, 2, 3 형태의 문자열로 만듭니다.
            page_text = ", ".join(page_texts)


            # 첫 번째 검색 결과에서 파일 이름을 가져옵니다.
            filename = result["sources"][0]["file"]


            # 참고 문서와 페이지 정보를 출력합니다.
            st.caption(
                f"※ 참고: {filename} "
                f"{page_text}페이지"
            )