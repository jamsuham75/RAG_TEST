# ===================================================
# test_coverage.py
# 32차시 - 경로 커버리지 테스트
# ===================================================

import time

from collections import Counter

from graph32 import app, MAX_TOTAL_SEC
from graph_state2 import make_initial_state


# ===================================================
# 테스트 케이스
# ===================================================
# 각 질문은 서로 다른 그래프 경로를 확인하기 위한 것입니다.
# ===================================================

CASES = [

    (
        "안녕하세요",
        "greeting 경로"
    ),

    (
        "120 * 3 + 45",
        "calc 경로"
    ),

    (
        "오늘 날씨 어때요?",
        "scope 경로"
    ),

    (
        "환불은 며칠 이내인가요?",
        "정상 RAG 경로"
    ),

    (
        "반품하고 싶은데 언제까지?",
        "재검색 경로"
    ),

    (
        "환불 방법과 수수료는?",
        "재생성 경로"
    ),

    (
        "대표이사가 누구인가요?",
        "fallback 경로"
    ),
]


# ===================================================
# 노드별 방문 횟수
# ===================================================

visited = Counter()


# ===================================================
# 테스트 실행
# ===================================================

for question, description in CASES:

    # -----------------------------------------------
    # 초기 State 생성
    # -----------------------------------------------

    state = make_initial_state(
        question
    )


    # -----------------------------------------------
    # graph32.py의 ask()와 동일하게
    # 전체 실행 제한 시간 설정
    # -----------------------------------------------

    state["deadline"] = (
        time.time() + MAX_TOTAL_SEC
    )


    # -----------------------------------------------
    # 이번 질문에서 방문한 노드
    # -----------------------------------------------

    nodes = []


    # -----------------------------------------------
    # stream으로 노드 실행 과정 확인
    # -----------------------------------------------

    for step in app.stream(
        state,
        {
            "recursion_limit": 40
        },
    ):

        for node_name in step.keys():

            nodes.append(
                node_name
            )

            visited[node_name] += 1


    # -----------------------------------------------
    # 질문별 실행 경로 출력
    # -----------------------------------------------

    print(
        f"\n[{description}]"
    )

    print(
        f"  Q: {question}"
    )

    print(
        f"  경로: "
        f"{' -> '.join(nodes)}"
    )


# ===================================================
# 전체 결과
# ===================================================

print(
    f"\n{'=' * 55}"
)

print(
    "노드별 방문 횟수"
)


# ===================================================
# 반드시 한 번 이상 방문해야 하는 노드
# ===================================================

ALL_NODES = [

    "classify",

    "greeting",

    "calc",

    "scope",

    "retrieve",

    "generate",

    "verify",

    "bump",

    "rewrite",

    "fallback",
]


# ===================================================
# 노드별 커버리지 확인
# ===================================================

for node_name in ALL_NODES:

    if visited[node_name] > 0:

        mark = "✓"

    else:

        mark = "✗ 미방문!"


    print(
        f"  "
        f"{node_name:<10} "
        f"{visited[node_name]:>3}회  "
        f"{mark}"
    )


# ===================================================
# 최종 판정
# ===================================================

missing = [

    node_name

    for node_name in ALL_NODES

    if visited[node_name] == 0
]


print(
    f"{'=' * 55}"
)


if not missing:

    print(
        "✓ 모든 노드를 최소 1회 이상 방문했습니다."
    )

else:

    print(
        "✗ 방문하지 않은 노드가 있습니다."
    )

    print(
        "  미방문 노드: "
        + ", ".join(missing)
    )